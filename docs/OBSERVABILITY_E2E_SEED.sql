-- M4.2D3 — local development-only inventory provisioning for a fresh demo session.
-- This is the ONLY intentional SQL write in this validation package.
-- In Visual Studio -> SQL Server Object Explorer -> ConferenceProFlowAllocation -> New Query.
-- Replace the placeholder on the @SessionIdText line with the NEW id from HTTP request 02.
-- IMPORTANT: NEVER run against a production database. Do not reset/delete existing rows.
USE [ConferenceProFlowAllocation];
GO
SET NOCOUNT ON;

DECLARE @SessionIdText nvarchar(36) = N'PASTE-FRESH-SESSION-GUID-HERE';
DECLARE @SessionId uniqueidentifier = TRY_CONVERT(uniqueidentifier, @SessionIdText);
DECLARE @Capacity int = 2;

IF DB_NAME() <> N'ConferenceProFlowAllocation'
    THROW 51000, 'Wrong database. Use the local ConferenceProFlowAllocation database.', 1;
IF @SessionId IS NULL
    THROW 51001, 'Replace PASTE-FRESH-SESSION-GUID-HERE with the NEW session GUID from HTTP request 02.', 1;
IF @Capacity <= 0
    THROW 51002, 'Capacity must be positive.', 1;
IF EXISTS (SELECT 1 FROM dbo.SessionInventories WHERE SessionId = @SessionId)
    THROW 51003, 'Session inventory exists already. Use a fresh demo session.', 1;

INSERT INTO dbo.SessionInventories (SessionId, Capacity, ReservedCount, CreatedAtUtc)
VALUES (@SessionId, @Capacity, 0, TODATETIMEOFFSET(SYSUTCDATETIME(), '+00:00'));

SELECT SessionId, Capacity, ReservedCount, CreatedAtUtc, RowVersion
FROM dbo.SessionInventories WHERE SessionId = @SessionId;
-- Expected: Capacity=2, ReservedCount=0; RowVersion generated by SQL Server.
